"""Start/stop the GPS bridge foreground service from the main app.

Uses an Android Intent to start/stop the service (a Java class generated by
python-for-android). The service class name is based on the package name and
the service name declared in the build.
"""

import logging
import os

log = logging.getLogger("gnss-bridge.control")

# The service class name (package + service name). Override via env var if
# your package name differs.
SERVICE_CLASS = os.environ.get(
    "GPS_SERVICE_CLASS",
    "org.gnssbridge.app.ServiceGps",
)


def _activity():
    """Get the current Android Activity."""
    from jnius import autoclass

    PythonActivity = autoclass("org.kivy.android.PythonActivity")
    activity = PythonActivity.mActivity
    if activity is None:
        raise RuntimeError("No active Android activity")
    return activity


def start_service():
    """Start the GPS bridge foreground service.

    Uses the static start() method generated by python-for-android, which
    builds the Intent with all the extras the service needs (entrypoint,
    python path, foreground flag, ...). A raw Intent + startService() would
    crash in onStartCommand because those extras would be missing.
    """
    from jnius import autoclass

    ServiceClass = autoclass(SERVICE_CLASS)
    activity = _activity()
    ServiceClass.start(activity, "")
    log.info("Service start requested (%s)", SERVICE_CLASS)


def stop_service():
    """Stop the GPS bridge foreground service."""
    from jnius import autoclass

    ServiceClass = autoclass(SERVICE_CLASS)
    activity = _activity()
    ServiceClass.stop(activity)
    log.info("Service stop requested (%s)", SERVICE_CLASS)
